"""The Order Flow book panel's Playwright stubs for a closed market and a feed down are served.

They are what the route serves.

tests/e2e/console-order-flow-heatmap.spec.js and tests/e2e/console-trade-desk.spec.js draw
tests/e2e/fixtures/order_flow_book_closed_payload.json and order_flow_book_offline_payload.json.
Each file is GENERATED by the real route's producer (push.book.order_flow_microstructure), never
hand written:Schwab's NYSE_BOOK for SPY as sent on 2026-09-25
(tests/fixtures/real_spy_nyse_nasdaq_books.json) and SPY's LEVELONE_EQUITIES messages as sent on
2026-10-23, in order (tests/fixtures/real_spy_level_one_2026_10_23.json): two real captures that
were not received together, so the book is weeks older than the quote; the daemon's price row built
from it by the daemon's own function, served at 22:00 ET on 2026-10-23, when Schwab's /markets
answer for that date says the market is closed. STAND-IN (named): the daemon's status, its Schwab
socket open and holding SPY on LEVELONE_EQUITIES and NYSE_BOOK (for the books), and SPY or $SPX on
LEVELONE_EQUITIES (for tests/e2e/fixtures/price_rows_live.json); no status message is captured.

Regenerate (from the repo root, project .venv):
  python -c "import tests.conftest, tests.test_order_flow_book_payload_v1 as t
  t.write_book_e2e_fixture()"
"""

