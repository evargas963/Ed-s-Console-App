_FX = Path(__file__).resolve().parent / "fixtures"
_E2E_FIXTURE = (
    Path(__file__).resolve().parent / "e2e" / "fixtures" / "order_flow_book_closed_payload.json"
)
_E2E_OFFLINE = _E2E_FIXTURE.with_name("order_flow_book_offline_payload.json")
#: 2026-10-23 22:00 ET, after the quote: the stock market closed in Schwab's /markets answer for
#: that date
_CLOSED = datetime.fromisoformat("2026-10-23T22:00:00-04:00").timestamp()


def build_book_closed_payload(
    feed_down: bool = False, with_book: bool = True, at: float | None = None, without: str = ""
) -> dict:
    """Build the route's NYSE_BOOK payload for SPY at `at` (_CLOSED when None), from real data.

    The daemon's connection is up (NOT LIVE, the market closed), or ended after its row arrived
    (`feed_down`: OFFLINE). Without `with_book`, Schwab's NYSE_BOOK message is not sent; `without`
    names a side ("BIDS", "ASKS") the message is sent without (INDUCED).
    """
    when = _CLOSED if at is None else at
    book = json.loads((_FX / "real_spy_nyse_nasdaq_books.json").read_text(encoding="utf-8"))[
        "books"
    ]["NYSE_BOOK"]
    quotes = json.loads((_FX / "real_spy_level_one_2026_10_23.json").read_text(encoding="utf-8"))[
        "messages"
    ]
    # the books and readouts another test's SPY books left in this process are not this book's
    ofls.clear_all_live_state()
    try:
        lmp.record_feed_heartbeat(
            daemon_status(
                when,
                schwab_socket_open=True,
                held={"LEVELONE_EQUITIES": ["SPY"], "NYSE_BOOK": ["SPY"]},
            )
        )
        for m in sorted(
            quotes, key=lambda m: m["ts_recv"]
        ):  # each change as Schwab sent it, in order
            lmp.record_from_level_one_equity("SPY", m["item"], received_ts=m["ts_recv"])
        if with_book:
            ofs._ingest_pushed(
                "book.SPY",
                book_msg(
                    symbol="SPY",
                    service="NYSE_BOOK",
                    content={k: v for k, v in book["content"].items() if k != without},
                    src="schwab_book",
                    ts_recv=book["ts_recv"],
                ),
            )
        if feed_down:
            mark_feed_down()
        return json.loads(json.dumps(push_book.order_flow_microstructure("SPY", "NYSE_BOOK", when)))
    finally:
        for kept in (lmp._by_ticker, lmp._fields_by_ticker):
            kept.pop("SPY", None)
        mark_feed_down()
        ofls.clear_all_live_state()


#: 2026-10-23 15:59:05 ET, regular hours, the last of the five captured SPY messages received
_RTH = datetime.fromisoformat("2026-10-23T15:59:05-04:00").timestamp()
#: 2026-10-19 10:00 ET, regular hours, after $SPX's captured 09:30 message
_SPX_RTH = datetime.fromisoformat("2026-10-19T10:00:00-04:00").timestamp()
_E2E_ROWS = _E2E_FIXTURE.with_name("price_rows_live.json")
_E2E_NO_BOOK = _E2E_FIXTURE.with_name("order_flow_book_none_payload.json")


def _row_after(ticker: str, messages: list, at: float) -> dict:
    """Return the daemon's price row for `ticker` at `at` after its real messages.

    The row is live_price_rows.price_row's, the daemon holding it: what the daemon's price socket
    pushes to the page.
    """
    try:
        lmp.record_feed_heartbeat(
            daemon_status(at, schwab_socket_open=True, held={"LEVELONE_EQUITIES": [ticker]})
        )
        for m in sorted(messages, key=lambda m: m["ts_recv"]):
            lmp.record_from_level_one_equity(ticker, m["item"], received_ts=m["ts_recv"])
        return json.loads(json.dumps(live_price_rows.price_row(ticker, at)))
    finally:
        for kept in (lmp._by_ticker, lmp._fields_by_ticker):
            kept.pop(ticker, None)
        mark_feed_down()


def build_price_rows() -> dict:
    """Ticker -> the daemon's live row.

    SPY's at _RTH after its 2026-10-23 messages, and $SPX's at _SPX_RTH after its 2026-10-19
    09:30 message (tests/fixtures/real_security_status_2026_10_19.json).
    """
    spy = json.loads((_FX / "real_spy_level_one_2026_10_23.json").read_text(encoding="utf-8"))[
        "messages"
    ]
    spx = [
        m
        for m in json.loads(
            (_FX / "real_security_status_2026_10_19.json").read_text(encoding="utf-8")
        )["messages"]
        if m["symbol"] == "$SPX" and m["item"]["SECURITY_STATUS"] == "Normal"
    ]
    return {"SPY": _row_after("SPY", spy, _RTH), "$SPX": _row_after("$SPX", spx, _SPX_RTH)}


def write_book_e2e_fixture() -> None:
    """Regeneration utility (never called by a test).

    Schwab's /markets answers held as the tests hold them (tests/conftest.py), then the route's
    payload written to the e2e fixture.
    """
    for a in json.loads(MARKETS_ANSWERS.read_text(encoding="utf-8"))["answers"].values():
        if a["status"] == 200:
            record_markets(json.loads(a["body"]))
    for path, down in ((_E2E_FIXTURE, False), (_E2E_OFFLINE, True)):
        path.write_text(
            json.dumps(build_book_closed_payload(down), indent=2, sort_keys=True) + "\n",
            encoding="utf-8",
        )
    _E2E_NO_BOOK.write_text(
        json.dumps(build_book_closed_payload(with_book=False, at=_RTH), indent=2, sort_keys=True)
        + "\n",
        encoding="utf-8",
    )
    _E2E_ROWS.write_text(
        json.dumps(build_price_rows(), indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )


def _same(fixture, live):
    """Every key and value equal; a float to 1e-9 relative."""
    if isinstance(fixture, dict) and isinstance(live, dict):
        return fixture.keys() == live.keys() and all(_same(fixture[k], live[k]) for k in fixture)
    if isinstance(fixture, list) and isinstance(live, list):
        return len(fixture) == len(live) and all(_same(a, b) for a, b in zip(fixture, live))
    if isinstance(fixture, float) and isinstance(live, float):
        return live == pytest.approx(fixture, rel=1e-9)
    return fixture == live


def test_the_closed_market_book_fixture_is_the_route_contract():
    """The committed Playwright fixture is what the route serves for the real book and quote.

    At 22:00 ET, every key and value: the top of book and the book NOT LIVE, outside Schwab's
    market hours.
    """
    fixture = json.loads(_E2E_FIXTURE.read_text(encoding="utf-8"))
    live = build_book_closed_payload()
    assert _same(fixture, live), (
        "E2E fixture drifted from the route; regenerate with write_book_e2e_fixture()"
    )
    assert (live["top_feed_label"], live["top_outage"], live["book_feed_label"]) == (
        "NOT LIVE",
        "outside Schwab's market hours",
        "NOT LIVE",
    )
    assert live["top_of_book"]["bid"] is not None and live["ages"]["book_stale"] is True


def test_the_live_price_rows_fixture_is_the_daemons_rows():
    """The committed price rows the desk's push-outage test draws are the daemon's own rows.

    For SPY's and $SPX's real messages in regular hours, every key and value: LIVE.
    """
    fixture = json.loads(_E2E_ROWS.read_text(encoding="utf-8"))
    live = build_price_rows()
    assert _same(fixture, live), (
        "E2E fixture drifted from the daemon's rows; regenerate with write_book_e2e_fixture()"
    )
    assert [(r["ticker"], r["feed_label"], r["outage"]) for r in live.values()] == [
        ("SPY", "LIVE", None),
        ("$SPX", "LIVE", None),
    ]
    assert live["SPY"]["spot"] is not None and live["SPY"]["trade_time_ct"] is not None


def test_with_no_book_held_the_panel_says_why_by_its_cause():
    """P-24: no book of the venue held, the panel serves why, by the book's own live verdict.

    In regular hours, the feed up and SPY held on NYSE_BOOK, but no book sent (INDUCED: the real
    book withheld): Schwab has sent none. Outside the market's hours: the live rule's reason. The
    feed down: its reason. With a book: no such text. The committed no-book fixture is the
    route's payload.
    """
    live = build_book_closed_payload(with_book=False, at=_RTH)
    assert live["status"] == "no_book" and live["book_feed_label"] == "LIVE"
    assert live["no_book_text"] == "Schwab has sent no NYSE_BOOK book for SPY"
    assert _same(json.loads(_E2E_NO_BOOK.read_text(encoding="utf-8")), live), (
        "E2E fixture drifted from the route; regenerate with write_book_e2e_fixture()"
    )
    closed = build_book_closed_payload(with_book=False)
    assert closed["no_book_text"] == "outside Schwab's market hours"
    down = build_book_closed_payload(feed_down=True, with_book=False)
    assert down["no_book_text"] == "Schwab NYSE_BOOK feed down during Closed"
    assert build_book_closed_payload()["no_book_text"] is None
    # the book's state as every screen says it, the program's word (AGENTS.md rule 4)
    assert (live["state_word"], down["state_word"]) == ("NO BOOK", "NO BOOK")
    assert build_book_closed_payload()["state_word"] is None


def test_a_side_with_no_displayed_level_is_said_by_the_panel():
    """INDUCED: SPY's real NYSE_BOOK sent without its bids, then without its asks.

    The side with no level is said in the words the Book's ladder draws (AGENTS.md rule 4), the
    other side not; the real two-sided book says neither.
    """
    whole = build_book_closed_payload(at=_RTH)
    assert (whole["asks_none_said"], whole["bids_none_said"]) == (None, None)
    no_bids = build_book_closed_payload(at=_RTH, without="BIDS")
    assert no_bids["depth_pressure"]["ask"] and not no_bids["depth_pressure"]["bid"]
    assert (no_bids["asks_none_said"], no_bids["bids_none_said"]) == (None, "no displayed bids")
    no_asks = build_book_closed_payload(at=_RTH, without="ASKS")
    assert (no_asks["asks_none_said"], no_asks["bids_none_said"]) == ("no displayed asks", None)


def test_the_book_serves_its_levels_and_no_size_outlier_label():
    """Operator 2026-11-19: the book's "wall candidate" label and its 3x-the-median rule go.

    The 3x had no source. Schwab's real SPY NYSE_BOOK: the payload serves each level as sent and
    the ladder's scale (the largest size drawn), and no level is labeled or classified as a wall.
    """
    live = build_book_closed_payload()
    assert "wall_candidates" not in live
    assert "wall_candidates" not in live["classification"]
    levels = live["depth_pressure"]["bid"] + live["depth_pressure"]["ask"]
    assert levels and live["depth_pressure"]["max_volume"] == max(r["volume"] for r in levels)


