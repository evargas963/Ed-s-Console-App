"""The Order Flow book panel's Playwright stubs for a closed market and a feed down are what the route serves.

tests/e2e/console-order-flow-heatmap.spec.js and tests/e2e/console-trade-desk.spec.js draw
tests/e2e/fixtures/order_flow_book_closed_payload.json and order_flow_book_offline_payload.json.
Each file is GENERATED by the real route's producer (server.order_flow_microstructure), never hand
written: Schwab's NYSE_BOOK for SPY as sent (tests/fixtures/real_spy_nyse_nasdaq_books.json) and SPY's
LEVELONE_EQUITIES messages as sent, in order (tests/fixtures/real_spy_level_one_2026_10_23.json), the daemon's
price row built from it by the daemon's own function, served at 22:00 ET on 2026-10-23, when Schwab's
/markets answer for that date says the market is closed. STAND-IN (named): the daemon's status, its
Schwab socket open and holding SPY on LEVELONE_EQUITIES and NYSE_BOOK.

Regenerate (from the repo root, project .venv):
  python -c "from tests.test_order_flow_book_payload_v1 import write_book_e2e_fixture; write_book_e2e_fixture()"
"""
from __future__ import annotations

import json
from datetime import datetime
from pathlib import Path

import pytest

_FX = Path(__file__).resolve().parent / "fixtures"
_E2E_FIXTURE = Path(__file__).resolve().parent / "e2e" / "fixtures" / "order_flow_book_closed_payload.json"
_E2E_OFFLINE = _E2E_FIXTURE.with_name("order_flow_book_offline_payload.json")
#: 2026-10-23 22:00 ET, after the quote: the stock market closed in Schwab's /markets answer for that date
_CLOSED = datetime.fromisoformat("2026-10-23T22:00:00-04:00").timestamp()


def build_book_closed_payload(feed_down: bool = False) -> dict:
    """The route's NYSE_BOOK payload for SPY at _CLOSED, from the real book and quotes: the daemon's
    connection up (NOT LIVE, the market closed), or ended after its row arrived (`feed_down`: OFFLINE)."""
    import app.options.order_flow.state as ofls
    import live_market_plane as lmp
    import server
    from app.options.order_flow import streaming as ofs
    from stream_spine import book_msg
    from tests.feed_live_helper import publish_daemon_rows

    book = json.loads((_FX / "real_spy_nyse_nasdaq_books.json").read_text(encoding="utf-8"))["books"]["NYSE_BOOK"]
    quotes = json.loads((_FX / "real_spy_level_one_2026_10_23.json").read_text(encoding="utf-8"))["messages"]
    ofls.clear_all_live_state()
    try:
        lmp.record_feed_heartbeat({"ts": _CLOSED, "schwab_socket_open": True,
                                   "held": {"LEVELONE_EQUITIES": ["SPY"], "NYSE_BOOK": ["SPY"]}})
        for m in sorted(quotes, key=lambda m: m["ts_recv"]):     # each change as Schwab sent it, in order
            lmp.record_from_level_one_equity("SPY", m["item"], received_ts=m["ts_recv"])
        publish_daemon_rows("SPY", now=_CLOSED)
        ofs._ingest_pushed("book.SPY", book_msg(symbol="SPY", service="NYSE_BOOK", content=book["content"],
                                                src="schwab_book", ts_recv=book["ts_recv"]))
        if feed_down:
            lmp.record_feed_down()
        return json.loads(json.dumps(server.order_flow_microstructure("SPY", "NYSE_BOOK", _CLOSED)))
    finally:
        ofs._price_rows.pop("SPY", None)
        for kept in (lmp._by_ticker, lmp._fields_by_ticker):
            kept.pop("SPY", None)
        lmp.record_feed_down()
        ofls.clear_all_live_state()


def write_book_e2e_fixture() -> None:
    """Regeneration utility (never called by a test): Schwab's /markets answers held as the tests hold
    them (tests/conftest.py), then the route's payload written to the e2e fixture."""
    from tests.conftest import MARKETS_ANSWERS
    from time_et import record_markets
    for a in json.loads(MARKETS_ANSWERS.read_text(encoding="utf-8"))["answers"].values():
        if a["status"] == 200:
            record_markets(json.loads(a["body"]))
    for path, down in ((_E2E_FIXTURE, False), (_E2E_OFFLINE, True)):
        path.write_text(json.dumps(build_book_closed_payload(down), indent=2, sort_keys=True) + "\n", encoding="utf-8")


def _same(fixture, live):
    """Every key and value equal; a float to 1e-9 relative."""
    if isinstance(fixture, dict) and isinstance(live, dict):
        return fixture.keys() == live.keys() and all(_same(fixture[k], live[k]) for k in fixture)
    if isinstance(fixture, list) and isinstance(live, list):
        return len(fixture) == len(live) and all(_same(a, b) for a, b in zip(fixture, live))
    if isinstance(fixture, float) and isinstance(live, float):
        return live == pytest.approx(fixture, rel=1e-9)
    return fixture == live


def test_the_closed_market_book_fixture_is_the_route_contract():
    """The committed Playwright fixture is what the route serves for the real book and quote at 22:00
    ET, every key and value: the top of book and the book NOT LIVE, outside Schwab's market hours."""
    fixture = json.loads(_E2E_FIXTURE.read_text(encoding="utf-8"))
    live = build_book_closed_payload()
    assert _same(fixture, live), "E2E fixture drifted from the route; regenerate with write_book_e2e_fixture()"
    assert (live["top_feed_label"], live["top_outage"], live["book_feed_label"]) == (
        "NOT LIVE", "outside Schwab's market hours", "NOT LIVE")
    assert live["top_of_book"]["bid"] is not None and live["ages"]["book_stale"] is True


def test_the_feed_down_book_fixture_is_the_route_contract():
    """The same with the daemon's connection ended: the last top of book stands, top and book OFFLINE."""
    fixture = json.loads(_E2E_OFFLINE.read_text(encoding="utf-8"))
    live = build_book_closed_payload(feed_down=True)
    assert _same(fixture, live), "E2E fixture drifted from the route; regenerate with write_book_e2e_fixture()"
    assert (live["top_feed_label"], live["top_outage"], live["book_feed_label"]) == (
        "OFFLINE", "Schwab LEVELONE_EQUITIES feed down during Closed", "OFFLINE")
    assert live["top_of_book"]["bid"] is not None and live["ages"]["book_stale"] is True
