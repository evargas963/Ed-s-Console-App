"""The Flow panel's Playwright stub is what the route serves (question 2: the screen shows it).

The Playwright Flow spec (tests/e2e/console-gamma-flow.spec.js) stubs
/api/order-flow/options-microstructure with tests/e2e/fixtures/options_microstructure_payload.json.
That file is GENERATED by the real route's producer (server.options_microstructure), never hand
written, from real Schwab messages: TSLA 2026-08-31 367.5 call's 12 LEVELONE_OPTIONS and 4
OPTIONS_BOOK messages as Schwab sent them (tests/fixtures/real_options_stream_history_samples.json,
observed 2026-08-31), applied by the console's own intake (streaming._ingest_pushed), valued at the
newest message's time. STAND-IN (named): the daemon's status, holding the contract on both
services.

Regenerate (from the repo root, project .venv):
  python -c "from tests.test_options_order_flow_production_v1 import write_flow_e2e_fixture; write_flow_e2e_fixture()"
"""
from __future__ import annotations

import json
import time
from pathlib import Path

import pytest

_HISTORY = Path(__file__).resolve().parent / "fixtures" / "real_options_stream_history_samples.json"
_FLOW_E2E_FIXTURE = Path(__file__).resolve().parent / "e2e" / "fixtures" / "options_microstructure_payload.json"
FLOW_CONTRACT = "TSLA  260831C00367500"


def build_flow_e2e_fixture_response() -> dict:
    """The route's payload for FLOW_CONTRACT after its real messages, at the newest one's time."""
    import app.options.order_flow.state as ofls
    import live_market_plane as lmp
    import server as srv
    from app.options.order_flow import streaming as ofs
    from stream_spine import book_msg, options_quote_msg

    events = next(c for c in json.loads(_HISTORY.read_text(encoding="utf-8"))["contracts"]
                  if c["symbol"] == FLOW_CONTRACT)["events"]
    ofls.clear_all_live_state()
    try:
        for e in sorted(events, key=lambda e: e["ts_recv"]):
            if e["kind"] == "book":
                ofs._ingest_pushed(f"book.{FLOW_CONTRACT}", book_msg(
                    symbol=FLOW_CONTRACT, service="OPTIONS_BOOK", content=e["content"], src="schwab_book",
                    ts_recv=e["ts_recv"]))
            else:
                ofs._ingest_pushed(f"optquote.{FLOW_CONTRACT}", options_quote_msg(
                    symbol=FLOW_CONTRACT, content=e["content"], src="schwab_options_l1", ts_recv=e["ts_recv"]))
        # the daemon's heartbeat, every second: its newest one, as the route reads
        lmp.record_feed_heartbeat({"ts": time.time(), "schwab_socket_open": True,
                                   "held": {"LEVELONE_OPTIONS": [FLOW_CONTRACT], "OPTIONS_BOOK": [FLOW_CONTRACT]}})
        return srv.options_microstructure(FLOW_CONTRACT, max(e["ts_recv"] for e in events))
    finally:
        lmp.record_feed_down()
        ofls.clear_all_live_state()


def write_flow_e2e_fixture() -> None:
    """Regeneration utility (never called by a test), in a child process with the same private
    runtime boundary tests/conftest.py applies, so the fixture never carries a live DB or token."""
    import os
    import shutil
    import subprocess
    import sys
    import tempfile

    root = tempfile.mkdtemp(prefix="ed-e2e-fixture-regen-")
    env = {k: v for k, v in os.environ.items()
           if k not in ("ED_CONSOLE_DB", "ED_DB_PATH", "STREAM_CAPTURE_DB_PATH")}
    env.update({"ED_RUNTIME_ROOT": root, "ED_ARTIFACTS_ROOT": os.path.join(root, "artifacts"),
                "ED_CONSOLE_ALLOW_NONCANONICAL_DB": "1", "ED_CI_OFFLINE": "1",
                "SCHWAB_API_KEY": "ci-placeholder-api-key", "SCHWAB_APP_SECRET": "ci-placeholder-app-secret",
                "SCHWAB_CALLBACK_URL": "https://127.0.0.1:8182"})
    code = ("import json, sys; from tests.test_options_order_flow_production_v1 import "
            "build_flow_e2e_fixture_response as b; sys.stdout.write(json.dumps(b()))")
    try:
        out = subprocess.run([sys.executable, "-c", code], env=env, capture_output=True, text=True, check=True,
                             cwd=str(_FLOW_E2E_FIXTURE.parents[3])).stdout
    finally:
        shutil.rmtree(root, ignore_errors=True)
    payload = json.loads(out.strip().splitlines()[-1])     # import-time log lines may precede it
    _FLOW_E2E_FIXTURE.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(f"wrote {_FLOW_E2E_FIXTURE}")


def _same(fixture, live):
    """Every key and value equal; a float to 1e-6 relative (a least-squares slope, `np.polyfit`,
    differs in its last digits between machines)."""
    if isinstance(fixture, dict) and isinstance(live, dict):
        return fixture.keys() == live.keys() and all(_same(fixture[k], live[k]) for k in fixture)
    if isinstance(fixture, list) and isinstance(live, list):
        return len(fixture) == len(live) and all(_same(a, b) for a, b in zip(fixture, live))
    if isinstance(fixture, float) and isinstance(live, float):
        return live == pytest.approx(fixture, rel=1e-6)
    return fixture == live


def test_flow_e2e_fixture_is_the_route_contract():
    """The committed Playwright fixture is what the route serves for these messages, every key and
    value, so the Flow spec proves the real API's output; the flow values it shows are served."""
    fixture = json.loads(_FLOW_E2E_FIXTURE.read_text(encoding="utf-8"))
    live = build_flow_e2e_fixture_response()
    assert _same(fixture, live), "E2E fixture drifted from the route; regenerate with write_flow_e2e_fixture()"
    assert fixture["status"] == "ok" and fixture["streaming_plane"]["subscription_state"] == "SUBSCRIBED"
    for k in ("tape_pressure_30s", "tape_pressure_2m", "tape_pressure_5m", "cum_delta_proxy", "top_book_pressure"):
        assert k not in live and fixture["flow"][k] is not None, k
