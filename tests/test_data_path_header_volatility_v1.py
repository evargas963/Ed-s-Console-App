"""The header's beats and market context are the daemon's own, while the indexes trade and after.

tests/e2e/console-header.spec.js draws tests/e2e/fixtures/header_volatility.json. The file is
GENERATED by the program's own producers, never hand written.

The market context's price rows are live_price_rows.price_row's for Schwab's full
LEVELONE_EQUITIES messages for $VIX, $SPX and $NDX of 2026-11-20, as sent
(tests/fixtures/real_market_context_level_one_2026_11_20.json), each served at its message's
receive time: 09:33:41 ET, in regular hours (`market_live`; `live` is $VIX's), and 16:28:26 ET,
after Schwab marked the indexes Closed (`market_closed`; `closed` is $VIX's). `market_down` is
the regular-hours rows as the daemon serves them while its Schwab socket is not open.

The beats are what the header reads of the daemon's status (capture.Daemon.status) at the first
of those instants (`beat_closed`: at the second): its clock, the session, the watchlist, the
sign-in Schwab accepts (capture.sign_in_line) and the database writer's status with Schwab's
five headlines of the open written (stream_spine.CaptureWriter on tests/fixtures/
real_schwab_news_headlines_2026_11_20.json). `beat_down` is that status of a daemon whose stream
has not logged in (its own words for it); `beat_not_recording` carries the writer's status
before it starts; `beat_refused` the sign-in Schwab refused on 2026-11-19
(tests/test_data_path_sign_in_v1.REFUSED_2026_11_19). STAND-IN (named): the daemon's status,
its Schwab socket open and holding the three indexes on LEVELONE_EQUITIES, its watchlist SPY; no
status message is captured.

Regenerate (from the repo root, project .venv), then Prettier, which sets a JSON file's layout:
  python -c "import tests.conftest, tests.test_data_path_header_volatility_v1 as t
  t.write_e2e_fixture()"
"""

from __future__ import annotations

import asyncio
import json
import tempfile
from pathlib import Path

import live_market_plane as lmp
import live_price_rows
from app.market_data.schwab.streaming.capture import sign_in_line
from app.market_data.schwab.streaming.live_push import MARKET_CONTEXT
from feed.connection import SCHWAB_CONNECTING
from stream_spine import LOG, CaptureWriter, MessageBus, verbatim_msg
from tests.conftest import MARKETS_ANSWERS
from tests.feed_live_helper import daemon_status, mark_feed_down
from tests.test_data_path_sign_in_v1 import REFUSED_2026_11_19
from time_et import record_markets

_FX = Path(__file__).resolve().parent / "fixtures"
_E2E = Path(__file__).resolve().parent / "e2e" / "fixtures" / "header_volatility.json"
_SENT = json.loads(
    (_FX / "real_market_context_level_one_2026_11_20.json").read_text(encoding="utf-8")
)["messages"]
#: Schwab's messages for the three indexes in regular hours, and once it marked them Closed
_AT_OPEN, _AT_CLOSE = _SENT[:3], _SENT[3:]
_OPEN, _CLOSED = _AT_OPEN[0], _AT_CLOSE[0]
#: Schwab's five headlines of the open, the rows the writer of the beats has written
_HEADLINES = json.loads(
    (_FX / "real_schwab_news_headlines_2026_11_20.json").read_text(encoding="utf-8")
)["messages"][:5]
#: what the page's header and rail read of the daemon's status
_HEADER_READS = (
    "ts",
    "clock_ct",
    "day_ct",
    "session",
    "session_word",
    "watchlist",
    "writer",
    "sign_in",
    "schwab_down",
)


def _rows_after(messages: list[dict], socket_open: bool = True) -> list[dict]:
    """Return the daemon's price rows for the market context after `messages`, in its order.

    Each is served at the last message's receive time, the daemon holding the three indexes on
    LEVELONE_EQUITIES with its Schwab socket open, or not.
    """
    at = messages[-1]["ts_recv"]
    try:
        lmp.record_feed_heartbeat(
            daemon_status(
                at,
                schwab_socket_open=socket_open,
                held={"LEVELONE_EQUITIES": list(MARKET_CONTEXT)},
            )
        )
        for m in messages:
            lmp.record_from_level_one_equity(m["symbol"], m["item"], received_ts=m["ts_recv"])
        return json.loads(json.dumps([live_price_rows.price_row(k, at) for k in MARKET_CONTEXT]))
    finally:
        for kept in (lmp._by_ticker, lmp._fields_by_ticker):
            for key in MARKET_CONTEXT:
                kept.pop(key, None)
        mark_feed_down()


def _recording(folder: Path) -> dict:
    """Return the status of a writer that has written Schwab's five headlines of the open."""

    async def go() -> dict:
        bus, stop = MessageBus(), asyncio.Event()
        writer = CaptureWriter(folder / "ed.db", batch_rows=1, batch_sec=0.01)
        task = asyncio.create_task(writer.run(bus.subscribe("", policy=LOG), stop=stop))
        for m in _HEADLINES:
            bus.publish(
                f"news.{m['symbol']}",
                verbatim_msg(
                    symbol=m["symbol"],
                    content=m["item"],
                    src="schwab_news",
                    ts_recv=m["ts_recv"],
                    schwab_ts=m["schwab_ts"],
                ),
            )
        async with asyncio.timeout(10):
            while writer.status()["rows_written"] < len(_HEADLINES) or writer.status()["held"]:
                await asyncio.sleep(0.02)
        status = writer.status()
        stop.set()
        await task
        return status

    return asyncio.run(go())


def build() -> dict:
    """Return what the header test's socket sends: the daemon's beats and the indexes' rows."""
    with tempfile.TemporaryDirectory() as folder:
        not_started = CaptureWriter(Path(folder) / "ed.db").status()
    with tempfile.TemporaryDirectory() as folder:
        recording = _recording(Path(folder))

    def beat(at: float = _OPEN["ts_recv"], **staged) -> dict:
        status = daemon_status(
            at,
            **{"watchlist": ["SPY"], "writer": recording, "sign_in": sign_in_line(None)} | staged,
        )
        return {k: status[k] for k in _HEADER_READS}

    market_live, market_closed = _rows_after(_AT_OPEN), _rows_after(_AT_OPEN + _AT_CLOSE)
    return json.loads(
        json.dumps(
            {
                "beat": beat(schwab_socket_open=True, schwab_down=None),
                "beat_closed": beat(
                    _AT_CLOSE[-1]["ts_recv"], schwab_socket_open=True, schwab_down=None
                ),
                "beat_down": beat(),
                "beat_not_recording": beat(
                    schwab_socket_open=True, schwab_down=None, writer=not_started
                ),
                "beat_refused": beat(
                    schwab_socket_open=True,
                    schwab_down=None,
                    sign_in=sign_in_line(REFUSED_2026_11_19),
                ),
                "live": market_live[MARKET_CONTEXT.index("$VIX")],
                "closed": market_closed[MARKET_CONTEXT.index("$VIX")],
                "market_live": market_live,
                "market_closed": market_closed,
                "market_down": _rows_after(_AT_OPEN, socket_open=False),
            }
        )
    )


def write_e2e_fixture() -> None:
    """Regeneration utility (never called by a test).

    Schwab's /markets answers held as the tests hold them (tests/conftest.py), then what the
    producers serve written to the e2e fixture.
    """
    for a in json.loads(MARKETS_ANSWERS.read_text(encoding="utf-8"))["answers"].values():
        if a["status"] == 200:
            record_markets(json.loads(a["body"]))
    _E2E.write_text(
        json.dumps(build(), indent=2, sort_keys=True) + "\n", encoding="utf-8", newline="\n"
    )


def test_the_header_fixture_is_the_daemons_rows_for_schwabs_vix_messages():
    """What the header test draws is the program's own, every key and value.

    In regular hours $VIX is LIVE with Schwab's last price, percent change and trade time. Once
    Schwab marks the index Closed, the stock session still open, its last value stands: NOT LIVE,
    why, its trade time and its age (AGENTS.md rule 5).
    """
    served = build()
    assert json.loads(_E2E.read_text(encoding="utf-8")) == served, (
        "E2E fixture drifted from the program's producers; regenerate with write_e2e_fixture()"
    )
    beat, live, closed = served["beat"], served["live"], served["closed"]
    assert (beat["clock_ct"], beat["day_ct"], beat["session"]) == (
        "08:33:41 CT",
        "Fri, Nov 20",
        "RTH",
    )
    late = served["beat_closed"]
    assert (late["clock_ct"], late["day_ct"], late["session"]) == (
        "15:28:26 CT",
        "Fri, Nov 20",
        "After-Hours",
    )
    # each session as the header says it, the program's word (AGENTS.md rule 4)
    assert (beat["session_word"], late["session_word"]) == ("REGULAR", "POST-MARKET")
    assert (live["feed_label"], live["outage"]) == ("LIVE", None)
    assert (live["spot"], live["spot_disp"]) == (_OPEN["item"]["LAST_PRICE"], "29.43")
    assert (live["chg_pct"], live["chg_pct_text"]) == (3.481013, "+3.48%")
    assert (live["trade_time_ct"], live["trade_age_text"]) == ("Fri 11/20 08:33 AM CT", "10s")
    assert (closed["feed_label"], closed["outage"]) == ("NOT LIVE", "Schwab marks $VIX Closed")
    assert (closed["spot"], closed["spot_disp"]) == (_CLOSED["item"]["LAST_PRICE"], "35.89")
    assert (closed["chg_pct"], closed["chg_pct_text"]) == (26.195499, "+26.20%")
    assert (closed["trade_time_ct"], closed["trade_age_text"]) == ("Fri 11/20 03:15 PM CT", "13m")


def test_the_market_context_rows_are_schwabs_three_indexes_as_sent():
    """Row 2's three cells: each index's last price and percent change as Schwab sent them.

    In regular hours all three are LIVE; once Schwab marked them Closed each stands NOT LIVE with
    its own trade time; with the daemon's Schwab socket not open each is OFFLINE, its last value
    standing, and the row says why.
    """
    served = build()
    assert [m["symbol"] for m in _AT_OPEN] == [m["symbol"] for m in _AT_CLOSE]
    assert sorted(m["symbol"] for m in _AT_OPEN) == sorted(MARKET_CONTEXT)
    sent = {m["symbol"]: m["item"] for m in _AT_OPEN}
    live = {r["ticker"]: r for r in served["market_live"]}
    assert [r["ticker"] for r in served["market_live"]] == list(MARKET_CONTEXT)
    assert all(
        r["feed_label"] == "LIVE" and r["spot"] == sent[k]["LAST_PRICE"] for k, r in live.items()
    )
    assert {k: (r["spot_disp"], r["chg_pct_text"]) for k, r in live.items()} == {
        "$SPX": ("7138.12", "-0.53%"),
        "$NDX": ("26126.19", "-1.47%"),
        "$VIX": ("29.43", "+3.48%"),
    }
    assert all(r["chg_pct"] == sent[k]["NET_CHANGE_PERCENT"] for k, r in live.items())
    # Schwab's quote time is the last time a bid or ask updated (Streamer API §3.1, field 34). An
    # index with neither, $VIX and $NDX here, is sent 0: no time, so none is served (the page draws
    # "-"); $SPX's is its own, 08:33:38 CT
    assert {k: (sent[k]["QUOTE_TIME_MILLIS"], r["quote_time_ct"]) for k, r in live.items()} == {
        "$SPX": (1795185218043, "Fri 11/20 08:33 AM CT"),
        "$NDX": (0, None),
        "$VIX": (0, None),
    }
    closed = {r["ticker"]: r for r in served["market_closed"]}
    shown = ("feed_label", "spot_disp", "chg_pct_text", "trade_time_ct", "trade_age_text")
    assert {k: tuple(r[f] for f in shown) for k, r in closed.items()} == {
        "$SPX": ("NOT LIVE", "6910.39", "-3.70%", "Fri 11/20 03:20 PM CT", "8m"),
        "$NDX": ("NOT LIVE", "25028.98", "-5.61%", "Fri 11/20 03:28 PM CT", "1s"),
        "$VIX": ("NOT LIVE", "35.89", "+26.20%", "Fri 11/20 03:15 PM CT", "13m"),
    }
    assert {r["outage"] for r in closed.values()} == {
        f"Schwab marks {k} Closed" for k in MARKET_CONTEXT
    }
    down = {r["ticker"]: r for r in served["market_down"]}
    assert all(
        (r["feed_live"], r["feed_label"], r["outage"], r["spot_disp"])
        == (False, "OFFLINE", "Schwab LEVELONE_EQUITIES feed down during RTH", live[k]["spot_disp"])
        for k, r in down.items()
    )


def test_the_beats_carry_the_recorders_word_the_sign_in_and_schwabs_connection():
    """What row 1's status cells and row 2's alert read, each the daemon's own.

    A writer that has written Schwab's five headlines says RECORDING with its whole line; one
    not started says so, and its class marks it. A daemon whose stream has not logged in says
    NOT CONNECTED. The sign-in is one word in its cell, with what to run and Schwab's own reason
    beside it for the alert.
    """
    served = build()
    writer = served["beat"]["writer"]
    assert (writer["word"], writer["cls"], writer["state"]) == ("RECORDING", "", "recording")
    assert writer["line"] == (
        "RECORDING · 5 rows · 0 failed, kept as sent · held in memory: 0 messages, 0.0 MB "
        "(0 waiting for the database) · 0 not recorded"
    )
    idle = served["beat_not_recording"]["writer"]
    assert (idle["word"], idle["cls"]) == ("NOT STARTED", "neg")
    assert idle["line"].startswith("NOT STARTED · 0 rows · ")
    assert served["beat"]["schwab_down"] is None
    assert served["beat_down"]["schwab_down"] == SCHWAB_CONNECTING
    assert SCHWAB_CONNECTING.startswith("NOT CONNECTED: ")
    assert served["beat"]["sign_in"]["word"] == "accepted"
    refused = served["beat_refused"]["sign_in"]
    assert (refused["word"], refused["cls"]) == ("REFUSED", "neg")
    assert refused["line"] == "REFUSED: run python reauth_schwab.py"
    assert refused["why"] == REFUSED_2026_11_19
